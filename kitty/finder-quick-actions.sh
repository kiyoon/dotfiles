#!/usr/bin/env bash
# Install the "Open in kitty" / "Open in kitty tab" Finder quick actions.
#
#   ./finder-quick-actions.sh              install into ~/Library/Services
#   ./finder-quick-actions.sh --uninstall  remove them
#   ./finder-quick-actions.sh --dest DIR   install somewhere else (tests)
#
# A quick action is an Automator .workflow bundle: an Info.plist declaring the
# Services menu entry, and a document.wflow holding a single Run Shell Script
# action. Both bundles are thin shims that call open-in-kitty.sh, so changing
# the behaviour means editing that script, not reinstalling these.

set -euo pipefail

DEST="$HOME/Library/Services"
UNINSTALL=0
DEST_IS_DEFAULT=1

while [[ $# -gt 0 ]]; do
	case "$1" in
	--dest)
		DEST="${2:?--dest needs a directory}"
		DEST_IS_DEFAULT=0
		shift 2
		;;
	--uninstall)
		UNINSTALL=1
		shift
		;;
	-h | --help)
		sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "unknown option: $1" >&2
		exit 1
		;;
	esac
done

WINDOW_ACTION="$DEST/Open in kitty.workflow"
TAB_ACTION="$DEST/Open in kitty tab.workflow"

if [[ $UNINSTALL -eq 1 ]]; then
	rm -rf "$WINDOW_ACTION" "$TAB_ACTION"
	echo "Removed both quick actions from $DEST"
	exit 0
fi

